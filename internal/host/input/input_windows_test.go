//go:build windows

package input

import "testing"

// TestWindowsHIDToVK validates the HID-usage-to-virtual-key mapping that the
// windows adapter uses. The mapping table is pure Go with no syscall
// dependency, so it compiles and runs on any host via cross-compilation.
func TestWindowsHIDToVK(t *testing.T) {
	cases := map[uint16]uint16{
		0x04: 0x41, // A
		0x1d: 0x5a, // Z
		0x1e: 0x31, // 1
		0x27: 0x30, // 0
		0x28: 0x0d, // Enter
		0x29: 0x1b, // Escape
		0x2a: 0x08, // Backspace
		0x2b: 0x09, // Tab
		0x2c: 0x20, // Space
		0x2d: 0xbd, // Minus
		0x2e: 0xbb, // Equal
		0x2f: 0xdb, // [
		0x30: 0xdd, // ]
		0x31: 0xdc, // \
		0x33: 0xba, // ;
		0x34: 0xde, // '
		0x35: 0xc0, // `
		0x36: 0xbc, // ,
		0x37: 0xbe, // .
		0x38: 0xbf, // /
		0x39: 0x14, // CapsLock
		0x3a: 0x70, // F1
		0x45: 0x7b, // F12
		0x49: 0x2d, // Insert
		0x4a: 0x24, // Home
		0x4b: 0x21, // PageUp
		0x4c: 0x2e, // Delete
		0x4d: 0x23, // End
		0x4e: 0x22, // PageDown
		0x4f: 0x27, // Right
		0x50: 0x25, // Left
		0x51: 0x28, // Down
		0x52: 0x26, // Up
		0xe0: 0xa2, // LeftControl
		0xe1: 0xa0, // LeftShift
		0xe2: 0xa4, // LeftAlt
		0xe3: 0x5b, // LeftGUI
		0xe4: 0xa3, // RightControl
		0xe5: 0xa1, // RightShift
		0xe6: 0xa6, // RightAlt
		0xe7: 0x5c, // RightGUI
	}
	for usage, want := range cases {
		if got, ok := hidToVK(usage); !ok || got != want {
			t.Errorf("hidToVK(%#x): got (%#x,%v), want (%#x,true)", usage, got, ok, want)
		}
	}
}

func TestWindowsHIDToVKRejectsReserved(t *testing.T) {
	if _, ok := hidToVK(0x1f); ok {
		t.Fatal("expected reserved usage 0x1f to be rejected")
	}
}
